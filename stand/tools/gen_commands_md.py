#!/usr/bin/env python3
"""Генерирует docs/COMMANDS.md из cmdmap.json — полный справочник команд."""
import json

m = json.load(open('cmdmap.json'))

# Ручные пояснения к разобранным командам/подкомандам.
NOTES_CMD = {
    '0x00': 'Проверка связи. Запрос 2 байта данных (адрес+код) + CRC = 4. Ответ — квитанция.',
    '0x01': 'Открытие канала связи. Байт 2 — уровень доступа (1 или 2), байты 3..8 — пароль (6). Длина 11.',
    '0x02': 'Закрытие канала. Сбрасывает права доступа. Длина 4.',
    '0x03': 'Запись параметров. Байт 2 — номер подкоманды (0..0x37), далее данные подкоманды.',
    '0x04': 'Запись расширенная (калибровка/режимы). Байт 2 — подкоманда, байт 3 — параметр.',
    '0x05': 'Чтение массивов данных. Байт 2 — тип, байт 3 — индекс. Длина 6.',
    '0x06': 'Специальные операции. Байт 2 — подкоманда, байты 3..5 — параметры. Длина 8.',
    '0x07': 'Чтение вспомогательных данных. Байт 2 — подкоманда.',
    '0x08': 'Чтение параметров. Байт 2 — подкоманда (0..0x29), для части — байт 3 — индекс.',
}
NOTES_SUB = {
    ('0x08', '0x00'): 'Серийный номер (4 байта, BE) + дата выпуска (3 байта) из INFO 0x1080. Ответ 7 байт.',
    ('0x08', '0x04'): 'Сетевой адрес узла. Ответ 1 байт (0x04FE / 0x04E1).',
    ('0x08', '0x05'): 'Сетевой адрес узла (дублирует 0x04). Ответ 1 байт.',
    ('0x08', '0x09'): 'Слово состояния (0x04F4/0x04F5) + режим (0x0839). Ответ 6 байт.',
    ('0x08', '0x1D'): 'Байт 0x02A8 (адрес/статус активного канала). Ответ 1 байт.',
    ('0x08', '0x29'): 'Мгновенные значения 3 фаз: A(0x03E8) B(0x03F8) C(0x0408), по 2 байта BE. Ответ 6 байт.',
    ('0x08', '0x1A'): 'Чтение калиброванной величины с индексом (байт 3, 1..4) и знаковой коррекцией по 0x0376/0x0378. Ответ 5 байт.',
    ('0x08', '0x11'): 'Счётчики энергии (0x0308/0x030A) + импульсные (0x0368). Ответ 2 байта.',
    ('0x03', '0x05'): 'Установка сетевого адреса узла (0x04FE) из байта запроса.',
    ('0x03', '0x14'): 'Настройка второго канала/адреса (0x04E1) и физического уровня (0x05A0/0x083A).',
    ('0x03', '0x37'): 'Сброс/установка счётчиков энергии (0x0300..0x030E).',
    ('0x05', '0x00'): 'Чтение массива тип 0 (журнал/таблица) по индексу.',
}


def bytefmt(lst):
    return '[' + ', '.join('#%d' % x for x in lst) + ']' if lst else '—'


lines = ['# Полный справочник команд стенда', '',
         'Сгенерировано автоматически из дизассемблированной прошивки '
         '(`tools/build_cmdmap.py` → `cmdmap.json`). Сигнатуры (длина, поля '
         'запроса/ответа, затронутые ячейки) извлечены анализом потока управления '
         'каждого обработчика; пояснения — по ручному разбору.', '',
         'Формат кадра: `[ADDR][CMD][подкоманда/аргументы][CRC_lo][CRC_hi]`, '
         'CRC-16/MODBUS. Подробности — в `PROTOCOL.md`.', '',
         '**Обозначения:** `len` — допустимая полная длина кадра (проверка `cmp #N,r8`); '
         '`req` — смещения байтов-аргументов в запросе; `resp` — число байт данных в ответе; '
         '`данные` — характерные ячейки RAM/INFO, которые обработчик читает(r)/пишет(w).', '']

for c in sorted(m):
    e = m[c]
    t = e['top']
    lines.append('## CMD %s — %s' % (c, e['name']))
    lines.append('')
    lines.append('*Обработчик 0x%04X. len=%s, req=%s.*' % (
        e['handler'], bytefmt(t['cmps']), bytefmt(t['req'])))
    if c in NOTES_CMD:
        lines.append('')
        lines.append(NOTES_CMD[c])
    lines.append('')
    if 'subs' in e:
        lines.append('Таблица подкоманд @0x%04X:' % e['sub_table'])
        lines.append('')
        lines.append('| Подкоманда | Обработчик | len | req | resp | читает | пишет |')
        lines.append('|---|---|---|---|---|---|---|')
        for s in sorted(e['subs']):
            h = e['subs'][s]
            rd = ' '.join(h['reads'][:6]) or '—'
            wr = ' '.join(h['writes'][:6]) or '—'
            lines.append('| %s | 0x%04X | %s | %s | %d | %s | %s |' % (
                s, h['handler'], bytefmt(h['cmps']), bytefmt(h['req']),
                len(h['resp']), rd, wr))
            note = NOTES_SUB.get((c, s))
            if note:
                lines.append('| | | | | | | %s |' % note)
        lines.append('')

open('../docs/COMMANDS.md', 'w').write('\n'.join(lines))
print('docs/COMMANDS.md:', len(lines), 'строк')
