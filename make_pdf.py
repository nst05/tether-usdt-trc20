HEADER_BG  = (30,  80,  162)
HEADER_FG  = (255, 255, 255)
CODE_BG    = (240, 255, 240)
CODE_BORDER= (34,  139, 34)
SECTION_H  = (30,  80,  162)
SUBHEAD    = (20,  110, 20)
HIGH_C     = (180, 30,  30)
MED_C      = (180, 120, 0)
LOW_C      = (30,  80,  162)
INFO_C     = (90,  90,  90)

class PDF(FPDF):
    def __init__(self):
        super().__init__()
        self.add_font("R", "", FONT_R)
        self.add_font("R", "B", FONT_B)
        self.add_font("M", "", FONT_M)
        self.set_auto_page_break(auto=True, margin=20)
        self.set_margins(20, 20, 20)

    def header(self):
        self.set_fill_color(*HEADER_BG)
        self.set_text_color(*HEADER_FG)
        self.set_font("R", "B", 11)
        self.cell(0, 10, "NEXUS PENTEST — Инструкция пользователя",
                  align="C", fill=True,
                  new_x=XPos.LMARGIN, new_y=YPos.NEXT)
        self.set_text_color(*TEXT)
        self.ln(2)

    def footer(self):
        self.set_y(-15)
        self.set_font("R", "", 8)
        self.set_text_color(120, 120, 120)
        self.cell(0, 10, f"Стр. {self.page_no()}", align="C")

    # ── helpers ──────────────────────────────────────────────────────────────

    def section_title(self, text):
        self.ln(4)
        self.set_fill_color(*SECTION_H)
        self.set_text_color(*HEADER_FG)
        self.set_font("R", "B", 13)
        self.cell(0, 10, text, fill=True, align="L",
                  new_x=XPos.LMARGIN, new_y=YPos.NEXT)
        self.set_text_color(*TEXT)
        self.ln(2)

    def sub(self, text):
        self.ln(3)
        self.set_text_color(*SUBHEAD)
        self.set_font("R", "B", 11)
        self.multi_cell(0, 7, text, new_x=XPos.LMARGIN, new_y=YPos.NEXT)
        self.set_text_color(*TEXT)

    def body(self, text):
        self.set_font("R", "", 10)
        self.set_text_color(*TEXT)
        self.multi_cell(0, 6, text, new_x=XPos.LMARGIN, new_y=YPos.NEXT)
        self.ln(1)

    def step(self, n, text):
        self.set_font("R", "B", 10)
        self.set_text_color(*TEXT)
        bullet = f"  {n}. "
        self.cell(self.get_string_width(bullet)+1, 6, bullet, new_x=XPos.END, new_y=YPos.TOP)
        self.set_font("R", "", 10)
        self.multi_cell(0, 6, text, new_x=XPos.LMARGIN, new_y=YPos.NEXT)

    def code(self, text):
        self.ln(1)
        self.set_fill_color(*CODE_BG)
        self.set_draw_color(*CODE_BORDER)
        self.set_font("M", "", 9)
        self.set_text_color(20, 80, 20)
        self.multi_cell(0, 6, text, border=1, fill=True,
                        new_x=XPos.LMARGIN, new_y=YPos.NEXT)
        self.set_text_color(*TEXT)
        self.ln(1)

    def note(self, text):
        self.set_fill_color(255, 248, 220)
        self.set_draw_color(200, 160, 0)
        self.set_font("R", "", 9)
        self.set_text_color(100, 70, 0)
        self.multi_cell(0, 6, "  ВАЖНО: " + text, border=1, fill=True,
                        new_x=XPos.LMARGIN, new_y=YPos.NEXT)
        self.set_text_color(*TEXT)
        self.ln(1)

    def colored_bullet(self, color, label, desc):
        self.set_font("R", "B", 10)
        self.set_text_color(*color)
        self.cell(30, 6, label, new_x=XPos.END, new_y=YPos.TOP)
        self.set_font("R", "", 10)
        self.set_text_color(*TEXT)
        self.multi_cell(0, 6, desc, new_x=XPos.LMARGIN, new_y=YPos.NEXT)

